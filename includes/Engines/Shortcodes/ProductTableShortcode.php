<?php
namespace YayBulkOrder\Engines\Shortcodes;

use YayBulkOrder\Services\ProductTablesService;
use YayBulkOrder\Utils\SingletonTrait;

defined( 'ABSPATH' ) || exit;

/**
 * Registers the [ybo-product-table] shortcode, rendering the default
 * Product Table block on the frontend outside the block editor.
 */
class ProductTableShortcode {
    use SingletonTrait;

    private const SHORTCODE_TAG = 'ybo-product-table';
    private ProductTablesService $product_tables_service;

    protected function __construct() {
        $this->product_tables_service = ProductTablesService::get_instance();
        add_shortcode( self::SHORTCODE_TAG, [ $this, 'render' ] );
    }

    /**
     * Render the default Product Table block markup.
     *
     * @param array $attrs shortcode attributes.
     * @return string
     */
    public function render( array $attrs ): string {
        if ( ! function_exists( 'WC' ) ) {
            return '';
        }

        $template = $this->is_product_archive() ? 'product-table-archive.php' : 'product-table-default.php';

        $attrs = $this->operate_shortcode_attrs( $attrs );

        ob_start();
        include YAYBULKORDER_PLUGIN_PATH . 'includes/Engines/Shortcodes/templates/' . $template;
        $markup = ob_get_clean();
        $html   = do_blocks( $markup );
        $html   = $this->clean_rendered_html( $html );
        return $html;
    }

    /**
     * Whether the current request is a WooCommerce product archive
     * (Shop, product category/tag, or any other product taxonomy archive).
     *
     * @return bool
     */
    private function is_product_archive(): bool {
        return is_shop() || is_product_taxonomy();
    }

    private function clean_rendered_html( string $html ): string {
        // Remove HTML comments.
        $html = preg_replace( '/<!--.*?-->/s', '', $html );

        // Remove empty paragraphs generated by wpautop().
        $html = preg_replace( '/<p[^>]*>\s*<\/p>/iu', '', $html );

        // Collapse line breaks.
        $html = preg_replace( '/\r\n|\r|\n/', ' ', $html );

        // Remove whitespace between HTML tags.
        $html = preg_replace( '/>\s+</', '><', $html );

        return trim( $html );
    }

    private function operate_shortcode_attrs( array $attrs ) {
        $raw_attrs = shortcode_atts(
            [
                'id'             => 0,
                'query_by'       => 'all',
                'categories'     => '',
                'products'       => '',
                'columns'        => 'product|Product|always-show,sku|SKU|hide-on-mobile,description|Description|always-show,quantity|Quantity|always-show,subtotal|Subtotal|hide-on-mobile,add-to-cart|Add To Cart|always-show',
                'has_filter'     => true,
                'has_search'     => true,
                'has_pagination' => true,
                'page_size'      => 0,
            ],
            $attrs,
            self::SHORTCODE_TAG,
        );

        if ( ! empty( $raw_attrs['id'] ) ) {
            $table = $this->product_tables_service->get_product_table_by_id( (int) $raw_attrs['id'] );
            if ( ! empty( $table ) ) {
                $enabled_columns = array_filter(
                    (array) $table['columns'],
                    static function ( $column ) {
                        return ! empty( $column['enabled'] );
                    }
                );

                // The admin Table Builder stores its category query mode as
                // 'by-categories' (ProductTablesService::QUERY_BY_OPTIONS),
                // but the query engine both this template and the block
                // editor share (ProductQueryService::get_product_query_restriction(),
                // query-types.ts) only recognizes the singular 'by-category'.
                $ybo_query_by_map = [ 'by-categories' => 'by-category' ];
                $ybo_table_query_by = $table['query']['queryBy'] ?? 'all';

                return [
                    'query_by'       => $ybo_query_by_map[ $ybo_table_query_by ] ?? $ybo_table_query_by,
                    'categories'     => array_values(
                        array_map( 'absint', (array) ( $table['query']['categories'] ?? [] ) )
                    ),
                    'products'       => array_values(
                        array_map( 'absint', (array) ( $table['query']['products'] ?? [] ) )
                    ),
                    'columns'        => $enabled_columns,
                    'has_filter'     => $table['features']['hasFilter'],
                    'has_search'     => $table['features']['hasSearch'],
                    'has_pagination' => $table['features']['hasPagination'],
                    'page_size'      => $table['features']['pageSize'] ?? 0,
                ];
            }//end if
        }//end if

        $raw_attrs['categories'] = explode( ',', $raw_attrs['categories'] );
        $raw_attrs['products']   = explode( ',', $raw_attrs['products'] );
        $raw_attrs['columns']    = $this->normalize_columns( $raw_attrs['columns'] );

        return $raw_attrs;
    }

    /**
     * Normalize the `columns` attribute into an ordered list of column configs.
     *
     * @param string|array $columns Raw columns data.
     * @return array<int, array{slug: string, heading: string, responsive: string}>
     */
    private function normalize_columns( $columns ): array {
        if ( is_string( $columns ) ) {
            $columns = explode( ',', $columns );
        }

        $normalized = [];

        foreach ( (array) $columns as $column ) {
            if ( is_array( $column ) ) {
                $slug       = $column['slug'] ?? '';
                $heading    = $column['heading'] ?? '';
                $responsive = $column['responsive'] ?? '';
            } else {
                [ $slug, $heading, $responsive ] = array_pad( explode( '|', (string) $column, 3 ), 3, '' );
            }

            $normalized[] = [
                'slug'       => $slug,
                'heading'    => $heading,
                'responsive' => in_array( $responsive, $this->product_tables_service::RESPONSIVE_OPTIONS, true ) ? $responsive : 'always-show',
            ];
        }

        return $normalized;
    }
}
