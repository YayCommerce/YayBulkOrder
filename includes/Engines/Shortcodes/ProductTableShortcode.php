<?php
namespace YayBulkOrder\Engines\Shortcodes;

use YayBulkOrder\Utils\SingletonTrait;

defined( 'ABSPATH' ) || exit;

/**
 * Registers the [ybo-product-table] shortcode, rendering the default
 * Product Table block on the frontend outside the block editor.
 */
class ProductTableShortcode {
    use SingletonTrait;

    private const SHORTCODE_TAG = 'ybo-product-table';

    protected function __construct() {
        add_shortcode( self::SHORTCODE_TAG, [ $this, 'render' ] );
    }

    /**
     * Render the default Product Table block markup.
     *
     * @return string
     */
    public function render(): string {
        if ( ! function_exists( 'WC' ) ) {
            return '';
        }

        $template = $this->is_product_archive() ? 'product-table-archive.php' : 'product-table-default.php';

        ob_start();
        include YAYBULKORDER_PLUGIN_PATH . 'includes/Engines/Shortcodes/templates/' . $template;
        $markup = ob_get_clean();
        $html   = do_blocks( $markup );
        $html   = $this->clean_rendered_html( $html );
        return $html;
    }

    /**
     * Whether the current request is a WooCommerce product archive
     * (Shop, product category/tag, or any other product taxonomy archive).
     *
     * @return bool
     */
    private function is_product_archive(): bool {
        return is_shop() || is_product_taxonomy();
    }

    private function clean_rendered_html( string $html ): string {
        // Remove HTML comments.
        $html = preg_replace( '/<!--.*?-->/s', '', $html );

        // Remove empty paragraphs generated by wpautop().
        $html = preg_replace( '/<p[^>]*>\s*<\/p>/iu', '', $html );

        // Collapse line breaks.
        $html = preg_replace( '/\r\n|\r|\n/', ' ', $html );

        // Remove whitespace between HTML tags.
        $html = preg_replace( '/>\s+</', '><', $html );

        return trim( $html );
    }
}
